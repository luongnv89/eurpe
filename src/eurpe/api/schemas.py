"""Pydantic models for the FastAPI ingestion wire format.

Why a wire model layer at all?
------------------------------
:class:`eurpe.schema.ProposalMetadata` is the *internal* model used by the
chunker, the index, and the YAML sidecar. Exposing it directly on the HTTP
boundary has two problems:

1. Internal fields drift. ``source_path`` is supplied by the server (it
   points at the staged PDF on disk); ``ingested_at`` is generated by the
   server. Letting clients write either field would either leak server
   paths into the request or let a misconfigured client overwrite the
   audit timestamp.
2. ``ProposalMetadata`` carries ``extra="forbid"`` for safety, which
   means *adding* a wire-only field (``parse_token``) would have to live
   somewhere else anyway.

The wire models below mirror only the fields the operator actually edits
in the React confirmation form; the route reconstructs the full
:class:`ProposalMetadata` server-side after lookup of the parse token.
``extra="forbid"`` is preserved on every wire model so an unexpected
field in the JSON body fails fast with a 422 instead of being silently
ignored.
"""

from __future__ import annotations

from datetime import datetime

from pydantic import BaseModel, ConfigDict, Field

from eurpe.schema import Programme, SectionType, SourceStatus


class ParseResponse(BaseModel):
    """What ``POST /api/ingestion/parse`` returns to the UI.

    The ``parse_token`` is a UUID4 string the client must echo back to
    ``POST /api/ingestion/confirm`` so the route can find the staged PDF
    and the server-extracted draft metadata. Tokens have a TTL (see
    :class:`eurpe.api.storage.ParseTokenStore`); expired tokens return
    ``404 Not Found`` from the confirm route.

    ``suggested`` is the best-effort metadata draft the server inferred
    from the filename plus any in-document hints. The UI pre-populates
    the confirmation form with these values; the operator is expected
    to review and override anything wrong.
    """

    model_config = ConfigDict(extra="forbid")

    parse_token: str = Field(min_length=1, description="Token to use with /confirm.")
    source_path: str = Field(min_length=1, description="Where the PDF was staged on disk.")
    parsed_at: datetime = Field(description="When the parser finished, UTC.")
    suggested: dict = Field(
        default_factory=dict,
        description=(
            "Best-effort metadata draft inferred from the filename, surfaced as a "
            "plain dict so the UI can render the values verbatim and let the "
            "operator override anything inferred wrongly."
        ),
    )
    page_count: int | None = Field(
        default=None,
        description="Page count reported by Docling, if available.",
    )
    title: str | None = Field(
        default=None,
        description="Document title recovered by Docling, if any.",
    )
    section_count: int = Field(
        default=0,
        description="How many top-level sections Docling extracted.",
    )


class ConfirmRequest(BaseModel):
    """Operator-confirmed metadata submitted to ``POST /api/ingestion/confirm``.

    Only the fields the operator can edit appear here. ``source_path`` and
    ``ingested_at`` are server-generated; ``language`` defaults to ``en`` to
    match :class:`ProposalMetadata` and may be overridden if needed.
    """

    model_config = ConfigDict(extra="forbid")

    parse_token: str = Field(min_length=1, description="Token from /parse.")
    programme: Programme = Field(description="Confirmed EU funding programme.")
    call_id: str = Field(
        min_length=1,
        description="Confirmed call identifier, e.g. HORIZON-CL5-2024-D3-02.",
    )
    topic_id: str = Field(min_length=1, description="Confirmed topic id within the call.")
    year: int = Field(ge=2014, le=2099, description="Call year (2014-2099).")
    outcome: SourceStatus = Field(
        description=(
            "Confirmed source-status of the proposal as a whole. The chunker "
            "stamps this onto every emitted chunk's ``source_status``; the "
            "metadata.py drift validator enforces equality."
        ),
    )
    proposal_title: str | None = Field(default=None, description="Optional proposal title.")
    consortium_acronym: str | None = Field(
        default=None,
        description="Optional consortium acronym, e.g. STP.",
    )
    language: str = Field(default="en", description="ISO 639-1 language code.")
    force: bool = Field(
        default=False,
        description=(
            "Override the soft-duplicate warning emitted when an existing "
            "record matches by (proposal_title, call_id) but the bytes differ. "
            "Has no effect on byte-identical (hard) duplicates."
        ),
    )


class ConfirmResponse(BaseModel):
    """What ``POST /api/ingestion/confirm`` returns once the chunks are indexed."""

    model_config = ConfigDict(extra="forbid")

    chunks_added: int = Field(ge=0, description="How many chunks landed in the index.")
    collection: str = Field(min_length=1, description="Chroma collection that received them.")
    sidecar_path: str = Field(
        min_length=1,
        description="Absolute path to the persisted YAML metadata sidecar.",
    )
    duplicate_warning: str | None = Field(
        default=None,
        description=(
            "Soft-duplicate warning surfaced when an existing record matches "
            "by (proposal_title, call_id) but the new content differs and the "
            "operator overrode the block via ``force=true``. ``None`` on the "
            "happy path."
        ),
    )
    replaced_document_id: str | None = Field(
        default=None,
        description=(
            "When non-null, the document_id whose chunks were deleted before "
            "this upsert. Set for the REINDEX (corrected-version) and forced "
            "soft-duplicate cases; ``None`` on a clean first-ingest."
        ),
    )


class EnumsResponse(BaseModel):
    """Closed enum values exposed to the UI so Selects never drift.

    The UI's programme / outcome dropdowns *must* source their options
    from this endpoint rather than hand-typing the strings. The route
    derives the lists from the Python enums directly so adding a new
    member upstream automatically appears in the form.
    """

    model_config = ConfigDict(extra="forbid")

    programme: list[str] = Field(description="Programme enum values.")
    source_status: list[str] = Field(description="SourceStatus enum values.")


